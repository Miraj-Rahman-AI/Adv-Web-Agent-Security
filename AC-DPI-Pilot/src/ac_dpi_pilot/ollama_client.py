import json
import urllib.error
import urllib.request

from ac_dpi_pilot.config import settings


class OllamaClient:
    """Client for a configurable Ollama service."""

    def __init__(self, base_url=None, timeout=None):

        self.base_url = (
            base_url or settings.ollama_base_url
        ).rstrip("/")

        self.timeout = timeout or settings.timeout

    def _request(self, method, endpoint, payload=None):

        url = f"{self.base_url}{endpoint}"

        data = None

        headers = {}

        if payload is not None:

            data = json.dumps(payload).encode("utf-8")

            headers["Content-Type"] = "application/json"

        request = urllib.request.Request(
            url=url,
            data=data,
            headers=headers,
            method=method
        )

        try:

            with urllib.request.urlopen(
                request,
                timeout=self.timeout
            ) as response:

                return json.loads(
                    response.read().decode("utf-8")
                )

        except urllib.error.HTTPError as error:

            raise RuntimeError(
                f"Ollama HTTP error: {error.code}"
            ) from error

        except urllib.error.URLError as error:

            raise RuntimeError(
                f"Cannot connect to configured Ollama service: "
                f"{error.reason}"
            ) from error

        except json.JSONDecodeError as error:

            raise RuntimeError(
                "Ollama returned an invalid JSON response."
            ) from error

    def list_models(self):

        response = self._request(
            "GET",
            "/api/tags"
        )

        return [
            item.get("name")
            for item in response.get("models", [])
        ]

    def chat(
        self,
        messages,
        model=None,
        temperature=None,
        num_predict=None,
        seed=None
    ):

        model = model or settings.default_model

        options = {
            "temperature": (
                settings.temperature
                if temperature is None
                else temperature
            ),
            "num_predict": (
                settings.num_predict
                if num_predict is None
                else num_predict
            )
        }

        if seed is not None:
            options["seed"] = seed

        payload = {
            "model": model,
            "messages": messages,
            "stream": False,
            "format": "json",
            "options": options
        }

        response = self._request(
            "POST",
            "/api/chat",
            payload
        )

        content = (
            response.get("message", {})
            .get("content", "")
        )

        if isinstance(content, dict):

            plan = content

            raw_output = json.dumps(
                content,
                ensure_ascii=False
            )

        else:

            raw_output = content

            try:

                plan = json.loads(content)

            except json.JSONDecodeError as error:

                raise ValueError(
                    f"Invalid JSON generated by model: {content}"
                ) from error

        if not isinstance(plan, dict):

            raise ValueError(
                "Model response must be a JSON object."
            )

        if not isinstance(plan.get("actions"), list):

            raise ValueError(
                "Model response must contain an actions list."
            )

        metadata = {
            key: response.get(key)
            for key in [
                "total_duration",
                "load_duration",
                "prompt_eval_count",
                "eval_count",
                "eval_duration"
            ]
        }

        return {
            "raw_output": raw_output,
            "plan": plan,
            "metadata": metadata
        }
